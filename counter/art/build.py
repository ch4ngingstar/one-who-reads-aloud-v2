"""Build the soul-shard counter art: validate, write PNGs, preview sheets and the Worker module.

    python counter/art/build.py            # build everything
    python counter/art/build.py --check    # validate only (CI)

Outputs
  counter/art/sprites/<digit>.png                 48x96 RGBA, palette colours only
  counter/art/preview/*.png                       lineups on dark / light at 1x, 2x and 4x
  counter/worker/src/sprites.generated.ts         base64 sprites + caption font (DESIGN.md 3.1)
"""
from __future__ import annotations

import argparse
import base64
import io
import json
from pathlib import Path
import sys

from PIL import Image

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from shard_cast import CAST  # noqa: E402
from shard_kit import CAPTION_FONT, H, SHARD_W, SHARD_X, SHARD_Y, W  # noqa: E402
from shard_palette import palette_rgb, rgb  # noqa: E402

SPRITES = HERE / "sprites"
PREVIEW = HERE / "preview"
GENERATED = HERE.parent / "worker" / "src" / "sprites.generated.ts"
BACKGROUNDS = {"dark": (13, 17, 23), "light": (255, 255, 255)}


class ArtError(Exception):
    pass


def validate(digit: str, img: Image.Image) -> None:
    if img.size != (W, H):
        raise ArtError(f"{digit}: size {img.size}, expected {(W, H)}")
    allowed = palette_rgb()
    px = img.load()
    for y in range(H):
        for x in range(W):
            r, g, b, a = px[x, y]
            if a not in (0, 255):
                raise ArtError(f"{digit}: semi-transparent pixel at {(x, y)}")
            if a and (r, g, b) not in allowed:
                raise ArtError(f"{digit}: off-palette colour {(r, g, b)} at {(x, y)}")
            if a and (x in (0, W - 1) or y in (0, H - 1)) and (r, g, b) != rgb("outline"):
                raise ArtError(f"{digit}: unoutlined pixel on the sprite edge at {(x, y)}")
    # The shard must sit exactly in its slot: its white tip is a fixed pixel.
    tip = px[SHARD_X + SHARD_W // 2, SHARD_Y + 1]
    if tuple(tip[:3]) not in (rgb("white"), rgb("violet")):
        raise ArtError(f"{digit}: soul shard missing from its slot")


def png_bytes(img: Image.Image) -> bytes:
    buf = io.BytesIO()
    img.save(buf, format="PNG", optimize=True)
    return buf.getvalue()


def lineup(images: "list[Image.Image]", scale: int, bg: "tuple[int, int, int] | None") -> Image.Image:
    sheet = Image.new("RGBA", (W * len(images) * scale, H * scale), (*bg, 255) if bg else (0, 0, 0, 0))
    for i, img in enumerate(images):
        sheet.alpha_composite(img.resize((W * scale, H * scale), Image.NEAREST), (i * W * scale, 0))
    return sheet


def typescript(pngs: "dict[str, bytes]") -> str:
    digits = ",\n".join(f"  {json.dumps(d)}: {json.dumps(base64.b64encode(data).decode())}"
                        for d, data in sorted(pngs.items()))
    glyphs = ",\n".join(f"    {json.dumps(ch)}: {json.dumps(rows)}" for ch, rows in CAPTION_FONT.items())
    return ("// Generated by counter/art/build.py — do not edit by hand.\n"
            "// Sprites: CC BY-NC 4.0 fan art of Shadow Slave (Guiltythree).\n\n"
            f"export const SPRITE_W = {W};\nexport const SPRITE_H = {H};\n\n"
            "/** Base64 PNGs (no data: prefix), keys \"0\"..\"9\". */\n"
            f"export const DIGITS: Record<string, string> = {{\n{digits}\n}};\n\n"
            "/** Pixel font for the caption: glyph rows of '#' (ink) and '.' (blank). */\n"
            "export const FONT: { width: number; height: number; glyphs: Record<string, string[]> } = {\n"
            "  width: 5,\n  height: 7,\n  glyphs: {\n" + glyphs + "\n  },\n};\n")


def build(check: bool = False) -> "dict[str, Image.Image]":
    images: dict[str, Image.Image] = {}
    for digit, (_name, draw) in sorted(CAST.items()):
        img = draw().render()
        validate(digit, img)
        images[digit] = img
    if check:
        return images
    SPRITES.mkdir(exist_ok=True)
    PREVIEW.mkdir(exist_ok=True)
    pngs = {}
    for digit, img in images.items():
        data = png_bytes(img)
        (SPRITES / f"{digit}.png").write_bytes(data)
        pngs[digit] = data
    ordered = [images[d] for d in sorted(images)]
    for bg_name, bg in BACKGROUNDS.items():
        for scale in (1, 2, 4):
            lineup(ordered, scale, bg).save(PREVIEW / f"cast-{bg_name}-{scale}x.png")
        lineup([images[d] for d in "0004182"], 2, bg).save(PREVIEW / f"counter-0004182-{bg_name}.png")
    GENERATED.parent.mkdir(parents=True, exist_ok=True)
    GENERATED.write_text(typescript(pngs), encoding="utf-8")
    print(f"built 10 sprites ({sum(len(v) for v in pngs.values())} bytes of PNG); previews in {PREVIEW}")
    return images


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    build(check=args.check)
    if args.check:
        print("art ok: 10 sprites valid")


if __name__ == "__main__":
    main()
